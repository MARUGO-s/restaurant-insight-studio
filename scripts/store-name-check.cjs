const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const root = path.resolve(__dirname, '..');
const ts = require('typescript');
const React = require('react');
const {renderToStaticMarkup} = require('react-dom/server');
const file = path.join(root, 'src/StoreNameInput.tsx');
assert(fs.existsSync(file), '店舗候補から選択できる自由入力コンポーネントが必要');
const mod = new Module(file); mod.filename = file; mod.paths = Module._nodeModulePaths(root);
mod._compile(ts.transpileModule(fs.readFileSync(file,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {StoreNameInput, STORE_NAMES, storeNameOptions, STORE_CATALOG, officialStoreUrl} = mod.exports;
assert(Array.isArray(STORE_CATALOG), '店舗ごとの公式URL定義が必要');
assert.equal(STORE_CATALOG.length, 23);
assert.equal(new Set(STORE_CATALOG.map(store => store.googleMapsUrl)).size, 23, 'maps URLs identify distinct stores');
for (const shop of STORE_CATALOG) {
  const maps = new URL(shop.googleMapsUrl);
  assert.equal(maps.protocol, 'https:');
  assert.ok(['www.google.com', 'www.google.co.jp', 'maps.app.goo.gl', 'maps.google.com'].includes(maps.hostname), shop.name);
  assert.ok(!shop.googleMapsUrl.includes('/maps/embed'), 'use a navigable Maps page, not an iframe');
 assert.equal(new URL(shop.url).protocol,'https:');
 assert.match(shop.tabelogUrl,/^https:\/\/tabelog\.com\/(tokyo|aichi)\/A\d+\/A\d+\/\d+\/$/);
}
assert.equal(new Set(STORE_CATALOG.map(shop=>shop.tabelogUrl)).size,23);
assert.equal(officialStoreUrl('マルゴ四谷'),'https://marugo-s.com/yotsuya/');
assert.equal(officialStoreUrl('マルゴ グランデ'),'https://marugo-s.com/g/');
assert.equal(officialStoreUrl('一覧外の店舗'),'');
assert.equal(STORE_NAMES.length, 23, '公式店舗一覧の全店舗を含む');
assert.equal(new Set(STORE_NAMES).size, STORE_NAMES.length);
assert(STORE_NAMES.includes('マルゴ 四谷'));
assert(STORE_NAMES.includes('マルゴ グランデ'));
assert(STORE_NAMES.includes('マルゴ D'));
assert.deepEqual(storeNameOptions('グランデ'), ['マルゴ グランデ']);
assert.deepEqual(storeNameOptions('マルゴ四谷'), ['マルゴ 四谷']);
assert.deepEqual(storeNameOptions('一覧にない店舗'), []);
assert.deepEqual(storeNameOptions(''), STORE_NAMES);
const html = renderToStaticMarkup(React.createElement(StoreNameInput, {value:'任意の店舗名',onChange:()=>{}}));
assert(html.includes('role="combobox"'));
assert(html.includes('value="任意の店舗名"'));
assert(html.includes('required=""'));
assert(html.includes('type="button"'));
assert(!html.includes('readonly'));
const app = fs.readFileSync(path.join(root,'src/App.tsx'),'utf8');
assert(app.includes('<StoreNameInput value={storeName} onChange={setStoreName}'), '既存stateへ接続');
assert(app.includes('setStoreUrl(store.url)'));
assert(app.includes('...urls, tabelog: store.tabelogUrl'));
console.log('PASS: 23 official/Tabelog/Google Maps URL triples, filtering, editable field, App URL state wiring');
